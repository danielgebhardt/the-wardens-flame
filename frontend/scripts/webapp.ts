/**
 * Vite plugin: the GitHub Pages build (`vite build --mode webapp`) becomes an installable,
 * offline web app ("Add to Home Screen" on iPhone/iPad, "Install app" in Android Chrome).
 *
 * In webapp builds it emits manifest.webmanifest, the icons in app-icons/ (made by
 * scripts/app-icons.py) and sw.js, and adds the manifest, icon and home-screen tags to
 * index.html. The dev server serves the same tags, manifest and icons, but no service worker.
 * iOS app builds only get viewport-fit=cover, so the game can pad itself clear of the notch.
 * Every other build (the Vercel website, the Android app) is left exactly as it was.
 *
 * The service worker precaches every built file. Page loads are network-first with a 4 s
 * timeout, so a new version shows on the next launch and a dead network falls back to the
 * cached page. Everything else is cache-first: file names are content-hashed.
 */
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import type { HtmlTagDescriptor, Plugin } from "vite";

const NAME = "The Warden's Flame";
const SHORT_NAME = "Warden's Flame";
// The Android launcher icon's background and the game's dark frame.
const BACKGROUND = "#140F0D";
const ICONS = [
	"icon-192.png",
	"icon-512.png",
	"icon-maskable-512.png",
	"apple-touch-icon.png",
] as const;

const icons = (): Record<string, Buffer> =>
	Object.fromEntries(
		ICONS.map((name) => [
			name,
			readFileSync(new URL(`../app-icons/${name}`, import.meta.url)),
		]),
	);

const manifest = () =>
	JSON.stringify(
		{
			name: NAME,
			short_name: SHORT_NAME,
			description:
				"Descend into the ruins, defeat the Ember Warden and bring its flame home.",
			id: "./",
			start_url: "./",
			scope: "./",
			display: "standalone",
			orientation: "portrait",
			background_color: BACKGROUND,
			theme_color: BACKGROUND,
			icons: [
				{ src: "icon-192.png", sizes: "192x192", type: "image/png" },
				{ src: "icon-512.png", sizes: "512x512", type: "image/png" },
				{
					src: "icon-maskable-512.png",
					sizes: "512x512",
					type: "image/png",
					purpose: "maskable",
				},
			],
		},
		null,
		2,
	);

const serviceWorker = (version: string, files: readonly string[]) =>
	`// Generated by scripts/webapp.ts
const CACHE = "wardens-flame-${version}";
const PRECACHE = ${JSON.stringify(["./", ...files])};
const INDEX = new URL("./", self.registration.scope).href;

self.addEventListener("install", (event) => {
	event.waitUntil(
		caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()),
	);
});

self.addEventListener("activate", (event) => {
	event.waitUntil(
		caches
			.keys()
			.then((keys) =>
				Promise.all(
					keys
						.filter((key) => key.startsWith("wardens-flame-") && key !== CACHE)
						.map((key) => caches.delete(key)),
				),
			)
			.then(() => self.clients.claim()),
	);
});

const timeout = (ms) =>
	new Promise((_, reject) => setTimeout(() => reject(new Error("timeout")), ms));

async function page(request) {
	const cache = await caches.open(CACHE);
	try {
		const response = await Promise.race([fetch(request), timeout(4000)]);
		if (response.ok) cache.put(INDEX, response.clone());
		return response;
	} catch {
		return (await cache.match(INDEX)) || Response.error();
	}
}

async function asset(request) {
	const hit = await caches.match(request);
	if (hit) return hit;
	const response = await fetch(request);
	if (response.ok) {
		const copy = response.clone();
		caches.open(CACHE).then((cache) => cache.put(request, copy));
	}
	return response;
}

self.addEventListener("fetch", (event) => {
	const request = event.request;
	if (request.method !== "GET" || new URL(request.url).origin !== location.origin) return;
	event.respondWith(request.mode === "navigate" ? page(request) : asset(request));
});
`;

const TOUCH_CALLOUT: HtmlTagDescriptor = {
	tag: "style",
	children:
		"html{-webkit-touch-callout:none;-webkit-tap-highlight-color:transparent}",
	injectTo: "head",
};

const homeScreenTags = (): HtmlTagDescriptor[] => [
	{
		tag: "link",
		attrs: { rel: "manifest", href: "./manifest.webmanifest" },
		injectTo: "head",
	},
	{
		tag: "link",
		attrs: { rel: "icon", type: "image/png", href: "./icon-192.png" },
		injectTo: "head",
	},
	{
		tag: "link",
		attrs: { rel: "apple-touch-icon", href: "./apple-touch-icon.png" },
		injectTo: "head",
	},
	{
		tag: "meta",
		attrs: { name: "theme-color", content: BACKGROUND },
		injectTo: "head",
	},
	{
		tag: "meta",
		attrs: { name: "mobile-web-app-capable", content: "yes" },
		injectTo: "head",
	},
	{
		tag: "meta",
		attrs: { name: "apple-mobile-web-app-capable", content: "yes" },
		injectTo: "head",
	},
	{
		tag: "meta",
		attrs: {
			name: "apple-mobile-web-app-status-bar-style",
			content: "black-translucent",
		},
		injectTo: "head",
	},
	{
		tag: "meta",
		attrs: { name: "apple-mobile-web-app-title", content: SHORT_NAME },
		injectTo: "head",
	},
	TOUCH_CALLOUT,
];

// The status bar sits over the page in the web app and the iOS app, so the page reaches the
// screen's edges and pads itself with env(safe-area-inset-*).
const coverViewport = (html: string) =>
	html.replace(
		/<meta name="viewport" content="([^"]*)"/,
		(_, content: string) =>
			`<meta name="viewport" content="${content}, viewport-fit=cover"`,
	);

export function webApp(mode: string): Plugin {
	let serving = false;
	return {
		name: "wardens-flame-webapp",
		// After Vite's own html plugin, so index.html is in the bundle for the precache list.
		enforce: "post",
		configResolved(config) {
			serving = config.command === "serve";
		},
		configureServer(server) {
			const files: Record<string, Buffer> = {
				...icons(),
				"manifest.webmanifest": Buffer.from(manifest()),
			};
			server.middlewares.use((request, response, next) => {
				const name = (request.url ?? "").split("?")[0].replace(/^\//, "");
				const body = files[name];
				if (!body) return next();
				response.setHeader(
					"Content-Type",
					name.endsWith(".png") ? "image/png" : "application/manifest+json",
				);
				response.end(body);
			});
		},
		transformIndexHtml(html) {
			if (mode === "webapp" || serving)
				return { html: coverViewport(html), tags: homeScreenTags() };
			if (mode === "ios")
				return { html: coverViewport(html), tags: [TOUCH_CALLOUT] };
			return html;
		},
		generateBundle(_options, bundle) {
			if (mode !== "webapp") return;
			const own: Record<string, string | Buffer> = {
				...icons(),
				"manifest.webmanifest": manifest(),
			};
			for (const [fileName, source] of Object.entries(own))
				this.emitFile({ type: "asset", fileName, source });
			// Files emitted here are not bundle keys yet, so they join the precache list by name.
			const built = Object.keys(bundle).filter(
				(file) => !file.endsWith(".map"),
			);
			const files = [...new Set([...built, ...Object.keys(own)])].sort();
			// Built file names carry content hashes, so the list itself versions the cache.
			const version = createHash("sha256")
				.update(files.join("\n"))
				.digest("hex")
				.slice(0, 12);
			this.emitFile({
				type: "asset",
				fileName: "sw.js",
				source: serviceWorker(version, files),
			});
		},
	};
}
